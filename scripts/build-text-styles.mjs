import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const outDir = path.join(root, 'src/styles/generated/text-styles');

/**
 * Figma composite text styles (Dev Mode paths like display/XS/regular).
 * Values resolve via tokens from 00 - xBase → 03 - typography / 02 - lineHeights.
 */
const TEXT_STYLE_CONFIG = [
  {
    role: 'display',
    sizes: ['xs', 's', 'm', 'l', 'xl'],
    weights: ['regular', 'medium'],
    letterSpacing: { kind: 'percent', value: -2 },
    fontSizeFallback: { xs: 40, s: 46, m: 52, l: 58, xl: 64 },
    lineHeightFallback: { xs: 40, s: 48, m: 52, l: 60, xl: 64 },
  },
  {
    role: 'headline',
    sizes: ['xs', 's', 'm', 'l', 'xl'],
    weights: ['regular', 'medium'],
    letterSpacing: { kind: 'percent', value: -1 },
    fontSizeFallback: { xs: 24, s: 28, m: 34, l: 40, xl: 46 },
    lineHeightFallback: { xs: 24, s: 28, m: 36, l: 40, xl: 48 },
  },
  {
    role: 'body',
    sizes: ['xs', 's', 'm', 'l', 'xl'],
    weights: ['regular', 'medium'],
    letterSpacing: { kind: 'percent', value: 0 },
    fontSizeFallback: { xs: 12, s: 14, m: 16, l: 18, xl: 24 },
    lineHeightFallback: { xs: 16, s: 16, m: 20, l: 20, xl: 28 },
    exceptions: {
      'xl-medium': { letterSpacing: { kind: 'px', value: -0.24 } },
    },
  },
  {
    role: 'special',
    sizes: ['one-size'],
    weights: ['medium'],
    letterSpacing: { kind: 'px', value: 0.88 },
    fontSizeFallback: { 'one-size': 11 },
    lineHeightFallback: { 'one-size': 12 },
    textTransform: 'uppercase',
  },
];

const WEIGHT_NUMERIC = { regular: 400, medium: 500 };

function figmaPath(role, size, weight) {
  const sizeLabel = size === 'one-size' ? 'oneSize' : size.toUpperCase();
  return `${role}/${sizeLabel}/${weight}`;
}

function tokenSuffix(role, size) {
  if (role === 'special') return 'special-one-size';
  return `${role}-${size}`;
}

function letterSpacingCss(config, role, size, weight) {
  const key = `${size}-${weight}`;
  const ls = config.exceptions?.[key] ?? config.letterSpacing;
  const suffix = tokenSuffix(role, size);
  const fsVar = `--font-sizes-${suffix}`;
  const fsFallback = config.fontSizeFallback[size];

  if (ls.kind === 'percent') {
    if (ls.value === 0) return 'letter-spacing: 0;';
    return `letter-spacing: calc(var(${fsVar}, ${fsFallback}) * ${ls.value / 100} * 1px);`;
  }
  return `letter-spacing: ${ls.value}px;`;
}

function buildStyleEntry(config, size, weight) {
  const { role } = config;
  const suffix = tokenSuffix(role, size);
  const className = `text-style--${role}-${size}-${weight}`;
  const figma = figmaPath(role, size, weight);
  const fsVar = `--font-sizes-${suffix}`;
  const lhVar = `--line-heights-${suffix}`;
  const fsFallback = config.fontSizeFallback[size];
  const lhFallback = config.lineHeightFallback[size];
  const weightNum = WEIGHT_NUMERIC[weight];

  const lines = [
    `/* Figma text style: ${figma} */`,
    `.${className} {`,
    `  font-size: calc(var(${fsVar}, ${fsFallback}) * 1px);`,
    `  line-height: calc(var(${lhVar}, ${lhFallback}) * 1px);`,
    `  ${letterSpacingCss(config, role, size, weight)}`,
    `  font-weight: ${weightNum};`,
    `  font-style: normal;`,
  ];
  if (config.textTransform) {
    lines.push(`  text-transform: ${config.textTransform};`);
  }
  lines.push('}');

  return {
    className,
    figma,
    role,
    size,
    weight,
    css: lines.join('\n'),
    manifest: {
      figmaPath: figma,
      className,
      role,
      size,
      weight,
      fontSizeToken: fsVar,
      lineHeightToken: lhVar,
      xBaseAliases: {
        fontSize: `fontSizes/${role}/${size === 'one-size' ? 'oneSize' : size.toUpperCase()} → fontSizes/base/*`,
        lineHeight: `lineHeights/${role}/${size === 'one-size' ? 'oneSize' : size.toUpperCase()} → lineHeights/base/* (mode-dependent)`,
      },
    },
  };
}

function buildAllStyles() {
  const entries = [];
  for (const config of TEXT_STYLE_CONFIG) {
    for (const size of config.sizes) {
      for (const weight of config.weights) {
        entries.push(buildStyleEntry(config, size, weight));
      }
    }
  }
  return entries;
}

async function main() {
  await mkdir(outDir, { recursive: true });

  const entries = buildAllStyles();
  const cssBlocks = entries.map((e) => e.css).join('\n\n');
  const header = `/**
 * Composite text styles (Figma 00---xBase variable bindings).
 * Generated by scripts/build-text-styles.mjs — do not edit directly.
 * Token sources: 00 - xBase, 02 - lineHeights, 03 - typography.
 */\n\n`;

  await writeFile(path.join(outDir, 'text-styles.css'), `${header}${cssBlocks}\n`);

  await writeFile(
    path.join(outDir, 'text-styles.json'),
    JSON.stringify(
      {
        source: '00 - xBase / 02 - lineHeights / 03 - typography',
        count: entries.length,
        styles: entries.map((e) => e.manifest),
      },
      null,
      2,
    ),
  );

  await writeFile(
    path.join(outDir, 'index.css'),
    `@import './text-styles.css';\n`,
  );

  console.log(`Built ${entries.length} text styles in src/styles/generated/text-styles/`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
